"""RQ3: common US earnings-event table -> SUE x HBR x stability regressions.

No independent data download or recomputation of SUE/CAR. Reads shared
`output/{industry}/events.csv` generated by src.did_us.run.save().
"""
from pathlib import Path
import numpy as np
import pandas as pd

from src.did_us.settings import INDUSTRIES, OUT_DIR

REQUIRED = ('eid','ticker','industry','quarter','sue','z_past','beat_rate_8q',
            'hist_sd','n_hist','n_beat_hist','car01','in_main_sample')


def load_events(root=OUT_DIR, industries=INDUSTRIES):
    frames=[]
    for industry in industries:
        path=Path(root)/industry/'events.csv'
        if not path.exists():
            raise FileNotFoundError(f'{path} missing. Run the shared pipeline first.')
        d=pd.read_csv(path)
        missing=set(REQUIRED)-set(d.columns)
        if missing: raise ValueError(f'{path}: missing columns {sorted(missing)}')
        if not d.industry.eq(industry).all(): raise ValueError(f'{path}: industry mismatch')
        frames.append(d)
    all_events=pd.concat(frames,ignore_index=True)
    if all_events.eid.duplicated().any(): raise ValueError('Duplicate event IDs in common events')
    return all_events


def make_sample(events, positive_only=True, full_eight=True, score='sue'):
    """Use EXACT common main sample; 8-history requirement is RQ3-specific.

    score='sue' is positive raw surprise (consistent with prior RQ3).
    score='z_past' is the firm's historical-standardized surprise (sensitivity).
    """
    if score not in ('sue','z_past'): raise ValueError('score must be sue or z_past')
    d=events.copy()
    main=d.in_main_sample.astype(str).str.lower().eq('true')
    d=d.loc[main].copy()
    if full_eight: d=d.loc[(d.n_hist>=8)&(d.n_beat_hist>=8)].copy()
    if positive_only: d=d.loc[d[score]>0].copy()
    d['SUE']=pd.to_numeric(d[score],errors='coerce')
    d['HBR']=pd.to_numeric(d.beat_rate_8q,errors='coerce')
    d['VolSUE']=pd.to_numeric(d.hist_sd,errors='coerce')
    d['CAR']=pd.to_numeric(d.car01,errors='coerce')
    d=d.replace([np.inf,-np.inf],np.nan).dropna(subset=['SUE','HBR','VolSUE','CAR','ticker','industry','quarter'])
    if d.empty: raise ValueError('No usable RQ3 events after filters')
    # Higher = more stable. Standardize VolSUE on pooled estimation sample.
    sd=d.VolSUE.std(ddof=1)
    if not np.isfinite(sd) or sd<=0: raise ValueError('VolSUE has no variation')
    d['Stability']=-(d.VolSUE-d.VolSUE.mean())/sd
    for col in ('SUE','HBR','Stability'):
        d[col+'_c']=d[col]-d[col].mean()
    return d


def fit_models(d):
    try:
        import statsmodels.formula.api as smf
    except ImportError as e:
        raise ImportError('Install statsmodels: pip install statsmodels') from e
    if d.ticker.nunique()<2: raise ValueError('Need >=2 firms for clustered SE')
    controls='C(industry) + C(quarter)'
    formulas={
        'rq2_same_sample':f'CAR ~ SUE_c * HBR_c + {controls}',
        'rq3_main':f'CAR ~ SUE_c * HBR_c * Stability_c + {controls}',
        'rq3_industry_heterogeneity':f'CAR ~ SUE_c * HBR_c * Stability_c * C(industry) + C(quarter)',
    }
    models={}
    rows=[]
    for name,formula in formulas.items():
        fit=smf.ols(formula,data=d).fit(cov_type='cluster',cov_kwds={'groups':d.ticker},use_t=True)
        models[name]=fit
        ci=fit.conf_int()
        for term in fit.params.index:
            rows.append(dict(model=name,term=term,coef=fit.params[term],se=fit.bse[term],
                             p=fit.pvalues[term],ci_low=ci.loc[term,0],ci_high=ci.loc[term,1],
                             n_events=int(fit.nobs),n_firms=d.ticker.nunique(),r_squared=fit.rsquared))
    return models,pd.DataFrame(rows)


def run_rq3(root=OUT_DIR,industries=INDUSTRIES,positive_only=True,full_eight=True,score='sue'):
    root=Path(root)
    ev=load_events(root,industries)
    d=make_sample(ev,positive_only=positive_only,full_eight=full_eight,score=score)
    models,results=fit_models(d)
    dest=root/'rq3'
    dest.mkdir(parents=True,exist_ok=True)
    d.to_csv(dest/'rq3_regression_sample.csv',index=False)
    results.to_csv(dest/'regression_results.csv',index=False)
    for name,fit in models.items():
        (dest/(name+'.txt')).write_text(fit.summary().as_text(),encoding='utf-8')
    summary=d.groupby('industry').agg(n_events=('eid','size'),n_firms=('ticker','nunique'),
             mean_sue=('SUE','mean'),mean_hbr=('HBR','mean'),
             mean_volsue=('VolSUE','mean'),mean_car=('CAR','mean')).reset_index()
    summary.to_csv(dest/'sector_comparison.csv',index=False)
    audit=(ev.groupby('industry').agg(all_events=('eid','size'),
              common_main_events=('in_main_sample',lambda x:x.astype(str).str.lower().eq('true').sum()))
           .reset_index().merge(summary[['industry','n_events','n_firms']],on='industry',how='left'))
    audit.to_csv(dest/'sample_audit.csv',index=False)
    return results,summary
